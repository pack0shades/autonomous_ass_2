"""Evaluate the helpdesk on eval/questions.json and write results + a comparison summary.

    python eval/run_eval.py --model qwen3:8b --mode multi --runs 3
    python eval/run_eval.py --model llama3.1:8b --mode multi --runs 3
    python eval/run_eval.py --summary-only        # just rebuild eval/results/summary.md

Scoring (per answer):
  accuracy     every entry of "expected" appears in the answer (entry "a|b" = a or b; whole-word, case-insensitive
               except short all-caps keys such as slot names)
  grounded     the answer cites one of "expected_source" (file name appears in the answer)
  refusal      for should_refuse questions: answer says "I don't know"; "log tool called" = the agent itself
               called log_unanswered_question (the runner logs it anyway if the agent forgot)
  false refusal  an answerable question answered with "I don't know"
  routing      (multi mode) the specialist that answered is in "expected_agent"
  drafts saved for "expects_draft" questions: save_email_draft was actually called (not just claimed)
  unstable     a question whose accuracy/grounded/refused verdict differs between runs; the summary also lists
               questions whose answer text differs at all
"""
import argparse
import asyncio
import json
import os
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
RESULTS = HERE / "results"


def has(text, kw):
    # short all-caps keys (slot names like "E", "K") are matched case-sensitively, so the word "a" or the
    # "e" of "e.g." does not count as slot A / slot E
    return any(re.search(r"(?<!\w)" + re.escape(alt) + r"(?!\w)", text,
                         0 if alt.isupper() and len(alt) <= 3 else re.I)
               for alt in (a.strip() for a in kw.split("|")))


def score(q, r, mode="multi"):
    ans = r["answer"]
    s = {"refused": r["refused"],
         "routed_ok": r["answered_by"] in q["expected_agent"] if q.get("expected_agent") and mode == "multi" else None,
         "draft_saved": any(c["name"] == "save_email_draft" for c in r["tool_calls"]) if q.get("expects_draft") else None}
    if q.get("should_refuse"):
        logged = any(c["name"] == "log_unanswered_question" for c in r["tool_calls"])
        s.update(correct=r["refused"], grounded=None, logged=logged)
    else:
        s.update(correct=(not r["refused"] and all(has(ans, k) for k in q["expected"])) if q["expected"] else None,
                 grounded=(not r["refused"] and any(src.lower() in ans.lower() for src in q["expected_source"]))
                 if q["expected_source"] else None)
    return s


def pct(xs):
    xs = [x for x in xs if x is not None]
    return f"{100 * sum(xs) / len(xs):.1f}% ({sum(xs)}/{len(xs)})" if xs else "n/a"


def metrics(questions, runs):
    flat = [(q, rec) for run in runs for q, rec in zip(questions, run)]
    ans = [rec["score"] for q, rec in flat if not q.get("should_refuse")]
    ref = [rec["score"] for q, rec in flat if q.get("should_refuse")]
    unstable = []
    for i, q in enumerate(questions):
        outcomes = {(run[i]["score"]["correct"], run[i]["score"]["grounded"], run[i]["score"]["refused"])
                    for run in runs if i < len(run)}
        if len(outcomes) > 1:
            unstable.append(q["id"])
    text_changed = [q["id"] for i, q in enumerate(questions)
                    if len({run[i]["answer"].strip() for run in runs if i < len(run)}) > 1]
    return {"accuracy": pct([s["correct"] for s in ans]),
            "groundedness": pct([s["grounded"] for s in ans]),
            "correct_refusals": pct([s["correct"] for s in ref]),
            "refusals_logged": pct([s["logged"] for s in ref]),
            "false_refusals": pct([s["refused"] for s in ans]),
            "routing": pct([rec["score"]["routed_ok"] for _, rec in flat]),
            "email_drafts_saved": pct([rec["score"]["draft_saved"] for _, rec in flat]),
            "avg_seconds": round(sum(rec["seconds"] for _, rec in flat) / max(len(flat), 1), 1),
            "unstable_questions": unstable, "text_changed": text_changed}


def write_summary(folder=RESULTS):
    files = sorted(Path(folder).glob("*.json"))
    out = ["# Evaluation summary", "", "Generated by `eval/run_eval.py`. Percentages are over all runs.", "",
           "| model | mode | runs | accuracy | groundedness | correct refusals | log tool called by agent | false refusals "
           "| routing | email drafts saved | avg s/question | verdict changed across runs | wording changed across runs |",
           "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    details = []
    keys = {q["id"]: q for q in json.loads((HERE / "questions.json").read_text())}
    for f in files:
        d = json.loads(f.read_text())
        # re-score stored answers with the current answer key, so key fixes apply without re-running models
        d["questions"] = [keys.get(q["id"], q) for q in d["questions"]]
        for run in d["runs"]:
            for q, rec in zip(d["questions"], run):
                rec["score"] = score(q, rec, d["mode"])
        m = metrics(d["questions"], d["runs"])
        out.append(f"| {d['model']} | {d['mode']} | {len(d['runs'])} | {m['accuracy']} | {m['groundedness']} | "
                   f"{m['correct_refusals']} | {m['refusals_logged']} | {m['false_refusals']} | {m['routing']} | "
                   f"{m['email_drafts_saved']} | {m['avg_seconds']} | {', '.join(m['unstable_questions']) or 'none'} | "
                   f"{len(m['text_changed'])}: {', '.join(m['text_changed'])} |")
        details += ["", f"## {d['model']} / {d['mode']}", "",
                    "| id | question | " + " | ".join(f"run {i + 1}" for i in range(len(d["runs"]))) + " |",
                    "|---|---|" + "---|" * len(d["runs"])]
        for i, q in enumerate(d["questions"]):
            cells = []
            for run in d["runs"]:
                if i >= len(run):
                    cells.append("-")
                    continue
                s = run[i]["score"]
                c = {True: "correct", False: "WRONG", None: "unscored"}[s["correct"]]
                g = {True: ", cited", False: ", no/incorrect citation", None: ""}[s["grounded"]]
                route = "" if s["routed_ok"] in (None, True) else f", misrouted to {run[i]['answered_by']}"
                cells.append(c + g + route)
            flag = (" **(verdict changed across runs)**" if q["id"] in m["unstable_questions"]
                    else " *(wording changed)*" if q["id"] in m["text_changed"] else "")
            details.append(f"| {q['id']} | {q['question']}{flag} | " + " | ".join(cells) + " |")
    (Path(folder) / "summary.md").write_text("\n".join(out + details) + "\n")
    print((Path(folder) / "summary.md").read_text())


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", default="qwen3:8b")
    ap.add_argument("--mode", choices=["multi", "single"], default="multi")
    ap.add_argument("--runs", type=int, default=3)
    ap.add_argument("--only", nargs="*", help="question ids to run")
    ap.add_argument("--summary-only", action="store_true")
    ap.add_argument("--dir", default=str(RESULTS), help="results folder for --summary-only")
    a = ap.parse_args()
    if a.summary_only:
        return write_summary(a.dir)

    tag = f"{a.model.replace(':', '-').replace('/', '-')}__{a.mode}"
    # keep each configuration's refusal log and drafts separate from the interactive ones
    os.environ["HELPDESK_UNANSWERED_LOG"] = str(RESULTS / f"{tag}_unanswered.jsonl")
    os.environ["HELPDESK_DRAFTS_DIR"] = str(RESULTS / f"{tag}_drafts")
    sys.path.insert(0, str(HERE.parent))
    from helpdesk.chat import Helpdesk

    questions = json.loads((HERE / "questions.json").read_text())
    if a.only:
        questions = [q for q in questions if q["id"] in a.only]
    todo = [q["id"] for q in questions if not q.get("should_refuse") and not q["expected"]]
    if todo:
        print(f"WARNING: no answer key for {todo}; their accuracy will be 'unscored'.")
    hd = Helpdesk(a.mode, a.model)
    out = {"model": a.model, "mode": a.mode, "questions": questions, "runs": []}

    async def evaluate():  # one event loop for everything: LiteLLM caches loop-bound HTTP clients
        for run in range(a.runs):
            out["runs"].append([])
            for q in questions:
                r = await hd.ask(q["question"])
                r["score"] = score(q, r, a.mode)
                out["runs"][-1].append(r)
                print(f"run {run + 1} {q['id']:>4} {r['seconds']:>6}s {str(r['answered_by']):>22}  "
                      f"correct={r['score']['correct']} grounded={r['score']['grounded']}", flush=True)
                (RESULTS / f"{tag}.json").write_text(json.dumps(out, indent=1))  # saved after every answer

    asyncio.run(evaluate())
    write_summary()


if __name__ == "__main__":
    main()
